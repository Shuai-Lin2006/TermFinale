def _set_lang(spec: LectureSpec) -> None:
    global LANG
    policy = spec.language_policy
    value = (policy.gen_lang or "").lower() if policy else ""
    LANG = "en" if value.startswith("english") else "hant" if value.startswith("繁") else "zh"


def _L() -> dict:
    return LABELS[LANG]


def _esc(text: str) -> str:
    return html.escape(text or "", quote=False)


def _visible_text(text: str) -> str:
    """Last line of defence against provider-escaped ``\n`` inside prose."""
    import re as _re
    text = _re.sub(r"\\r\\n", "\n", text or "")
    text = _re.sub(r"\\n(?=[\s(（\[【\u4e00-\u9fff。，；：！？、,.;:!?]|\d|$)", "\n", text)
    text = _re.sub(r"\\t(?=[\s(（])", " ", text)
    return text


def _protect_display_math(text: str) -> str:
    """Never inject <br> inside $$...$$; KaTeX needs the block intact.

    Models sometimes emit a display matrix inside an example paragraph. The
    paragraph renderer used to split all newlines into <br>, which breaks the
    math delimiter and leaves raw TeX in the PDF.
    """
    import re as _re

    def collapse(match: re.Match) -> str:
        inner = match.group(1)
        inner = _re.sub(r"[ \t]*\r?\n[ \t]*", " ", inner)
        return "$$" + inner + "$$"

    return _re.sub(r"\$\$(.+?)\$\$", collapse, text or "", flags=_re.S)


def _para(text: str) -> str:
    text = _protect_display_math(_visible_text(text))
    return "<br>".join(_esc(x) for x in text.splitlines() if x.strip())


def _display_page(ref: SourceRef, page: int) -> int:
    """把 artifact 页码换算回原始资料页码（有 source_page 时）。"""
    if ref.source_page is None:
        return page
    return ref.source_page + (page - ref.page_start)


def _material_label(material: str) -> str:
    text = (material or "").strip()
    if not text:
        return ""
    # ingest / scoped artifact 的 material 是内部 id，不能整串印给读者。
    stem = text.rsplit("/", 1)[-1]
    if len(stem) > 18 or stem.startswith(("gen_", "sel-", "merge-", "scoped_")):
        return stem[:14] + "…"
    return stem


def _pages_label(refs: list[SourceRef]) -> str:
    grouped: dict[str, list[int]] = {}
    order: list[str] = []
    for ref in refs:
        start = ref.page_start
        end = ref.page_end or start
        key = _material_label(ref.material)
        if key not in grouped:
            grouped[key] = []
            order.append(key)
        grouped[key].extend(_display_page(ref, p) for p in range(start, end + 1))
    multi = len([k for k in order if k]) > 1
    parts: list[str] = []
    for key in order:
        pages = sorted(set(grouped[key]))
        if not pages:
            continue
        ranges: list[str] = []
        i = 0
        while i < len(pages):
            j = i
            while j + 1 < len(pages) and pages[j + 1] == pages[j] + 1:
                j += 1
            ranges.append(f"{pages[i]}" if i == j else f"{pages[i]}–{pages[j]}")
            i = j + 1
        joined = "、" if LANG != "en" else ", "
        label = _L()["page"].format(p=joined.join(ranges))
        parts.append(f"《{key}》{label}" if (multi and key) else label)
    if not parts:
        return {"zh": "资料未标注页码", "hant": "資料未標註頁碼", "en": "No source pages"}[LANG]
    return ("；" if LANG != "en" else "; ").join(parts)


def _source_line(refs: list[SourceRef], cls: str = "source-line") -> str:
    if not refs:
        return ""
    return f'<p class="{cls}">{_L()["source"]}{_esc(_pages_label(refs))}</p>'




def _data_pages(refs: list[SourceRef]) -> str:
    pages: list[int] = []
    for ref in refs:
        start = ref.page_start
        end = ref.page_end or start
        pages.extend(range(start, end + 1))
    return f'data-pages="{",".join(map(str, sorted(set(pages))))}"' if pages else ""

def _figure(block: LectureBlock) -> str:
    fig = block.figure
    if fig is None:
        return ""
    if fig.asset_path:
        raw = str(fig.asset_path).replace("\\", "/")
        # 产物里的图片用相对路径：阅读器走 http 时 file:// 会被浏览器拦掉（图片全裂）。
        m = re.search(r"(?:^|/)((?:source_)?assets/[^/].*)$", raw)
        if m:
            src = m.group(1)
        else:
            p = Path(raw)
            src = p.resolve().as_uri() if p.is_absolute() else raw
        img = f'<img src="{_esc(src)}" alt="{_esc(fig.caption)}">'
    else:
        img = '<div class="figure-missing">图片缺失（需重新抽取）</div>'
    return (
        f'<figure id="{_esc(block.id)}" {_data_pages(block.source_refs)} class="figure-{_esc(fig.origin)}">{img}'
        f'<figcaption>{_esc(_visible_text(fig.caption))}</figcaption>'
        f'{_source_line([fig.source], "figure-source")}</figure>'
    )


def _strip_leading_label(text: str, labels: tuple[str, ...]) -> str:
    t = (text or "").lstrip()
    prefix = ""
    if t.startswith("【延伸】"):
        prefix = "【延伸】"
        t = t[len("【延伸】"):].lstrip()
    for label in labels:
        if t.startswith(label):
            return prefix + t[len(label):].lstrip("：: ")
    return prefix + t


def _formula_should_fallback(body: str) -> bool:
    # mhchem handles \ce natively; structures and unsupported arrows still fall back.
    if any(x in body for x in ("\\chemfig", "\\xrightarrow", "\\xleftarrow")):
        return True
    return False


def _formula_fallback_html(body: str) -> str:
    uri = formula_data_uri(body)
    if uri:
        return f'<img class="formula-img" alt="公式" src="{uri}">'
    return _esc(build_formula_asset(body).display)


def _safe_formula_prose(text: str) -> str:
    """Replace chemistry/structure formulas that KaTeX cannot render."""
    import re as _re
    def repl(m):
        body = m.group(1) if m.group(1) is not None else m.group(2)
        asset = build_formula_asset(body)
        if (_formula_should_fallback(body) or asset.kind == "structure"
                or asset.renderer != "typst"):
            return _formula_fallback_html(body)
        return m.group(0)
    return _re.sub(r"\$\$(.+?)\$\$|\$(.+?)\$", repl, text or "", flags=_re.S)


_PIPE_TABLE = re.compile(r"(?:^\|.+\|\s*$[\n\r]*)+", flags=re.M)


def _md_table_html(md: str) -> str:
    rows = [line for line in md.strip().splitlines() if line.strip()]
    def cells(line: str):
        return [c.strip() for c in line.strip().strip("|").split("|")]
    parts = ['<table class="md-table">', "<thead>"]
    body = []
    for idx, row in enumerate(rows):
        if idx == 1 and all(re.fullmatch(r":?-{1,}:?", c) for c in cells(row)):
            continue
        row_html = "<tr>" + "".join(f"<{('th' if idx == 0 else 'td')}>{_esc(c)}</{('th' if idx == 0 else 'td')}>" for c in cells(row)) + "</tr>"
        if idx == 0:
            parts.append(row_html)
        else:
            body.append(row_html)
    parts.append("</thead><tbody>")
    parts.extend(body)
    parts.append("</tbody></table>")
    return "".join(parts)


def _text_with_tables(text: str) -> str:
    parts = _PIPE_TABLE.split(text or "")
    tables = _PIPE_TABLE.findall(text or "")
    out = []
    for i, part in enumerate(parts):
        if part.strip():
            out.append(_para(_safe_formula_prose(part)))
        if i < len(tables):
            out.append(_md_table_html(tables[i]))
    return "\n".join(out) or _para(_safe_formula_prose(text or ""))


def _block(block: LectureBlock) -> str:
    if block.kind == BlockKind.FIGURE:
        return _figure(block)
    text = block.text
    if block.kind == BlockKind.EXAMPLE:
        # “例1：”“例 2:”这类编号不能和渲染器的“例题”标签重复。
        text = re.sub(r"^例\s*\d+\s*[：:]\s*", "", text)
        text = _strip_leading_label(text, ("例题：", "例题:", "例：", "例:"))
    elif block.kind == BlockKind.PITFALL:
        text = _strip_leading_label(text, ("易错点：", "易错点:", "易错：", "易错:"))
    elif block.kind == BlockKind.SUMMARY:
        text = _strip_leading_label(text, ("小结：", "小结:", "本节小结：", "本节小结:"))
    body = _text_with_tables(text)
    page_attr = _data_pages(block.source_refs)
    if block.kind == BlockKind.PARAGRAPH:
        return f'<p id="{_esc(block.id)}" {page_attr}>{body}</p>'
    if block.kind == BlockKind.CLAIM:
        return f'<p class="claim" id="{_esc(block.id)}" {page_attr}>{body}</p>'
    if block.kind == BlockKind.FORMULA:
        asset = build_formula_asset(text)
        if (_formula_should_fallback(text) or asset.kind == "structure"
                or asset.renderer != "typst"):
            body = _formula_fallback_html(text)
        return f'<div class="formula" id="{_esc(block.id)}" {page_attr}>{body}</div>'
    if block.kind == BlockKind.EXAMPLE:
        return f'<div class="example" id="{_esc(block.id)}" {page_attr}><span class="label">{_L()["example"]}</span>{body}</div>'
    if block.kind == BlockKind.PITFALL:
        return f'<div class="pitfall" id="{_esc(block.id)}" {page_attr}><span class="label">{_L()["pitfall"]}</span>{body}</div>'
    if block.kind == BlockKind.SUMMARY:
        return f'<div class="section-summary" id="{_esc(block.id)}" {page_attr}><span class="label">{_L()["block_summary"]}</span>{body}</div>'
    if block.kind == BlockKind.TABLE:
        return f'<div class="table-block" id="{_esc(block.id)}" {page_attr}><pre>{_esc(text)}</pre></div>'
    if block.kind == BlockKind.QUOTE:
        return f'<blockquote id="{_esc(block.id)}" {page_attr}>{body}</blockquote>'
    return f'<p id="{_esc(block.id)}" {page_attr}>{body}</p>'


def _section(sec: LectureSection, level: int = 2) -> str:
    h = f"h{level}"
    blocks = "\n".join(_block(b) for b in sec.blocks)
    summary = f'<p class="section-summary-text">{_para(sec.summary)}</p>' if sec.summary else ""
    meta = ""
    if getattr(sec, "objectives", None) or getattr(sec, "key_terms", None):
        objs = "".join(f"<li>{_esc(x)}</li>" for x in (sec.objectives or []))
        terms = "".join(f"<span>{_esc(x)}</span>" for x in (sec.key_terms or []))
        meta = (f'<div class="section-meta">'
                + (f'<div class="section-objectives"><b>{_L()["objectives"]}</b><ul>{objs}</ul></div>' if objs else "")
                + (f'<div class="section-terms"><b>{_L()["key_terms"]}</b><div>{terms}</div></div>' if terms else "")
                + '</div>')
    self_test = ""
    if getattr(sec, "self_test", None):
        qs = "".join(f"<li>{_esc(x)}</li>" for x in sec.self_test)
        self_test = f'<div class="self-test"><b>{_L()["self_test"]}</b><ol>{qs}</ol></div>'
    return (
        f'<section class="chapter" id="{_esc(sec.id)}">'
        f'<{h}>{_esc(sec.title)}</{h}>{meta}'
        f"{blocks}{summary}{self_test}{_source_line(sec.source_refs)}"
        f"</section>"
    )


def _cn_num(n: int) -> str:
    nums = "一二三四五六七八九十"
    return nums[n - 1] if 1 <= n <= 10 else str(n)


def _toc(spec: LectureSpec) -> str:
    if not spec.toc:
        return ""
    items = []
    section_no = 0
    for item in spec.toc:
        if item.level == 1:
            # The chapter is a heading, not a section row in the table of contents.
            section_no = 0
            items.append(
                f'<li class="toc-chapter"><a href="#{_esc(item.anchor)}">'
                f'<span>{_esc(item.title)}</span><span class="page">{item.page_no}</span></a></li>'
            )
            continue
        title = (item.title or "").strip()
        title = re.sub(r"^第[一二三四五六七八九十百0-9.]+[节節]\s*", "", title).strip()
        if not title:
            title = _L()["toc"]
        section_no += 1
        if LANG == "en":
            title = f"Section {section_no}: {title}"
        else:
            title = f"第{_cn_num(section_no)}{'節' if LANG == 'hant' else '节'} {title}"
        items.append(
            f'<li class="lvl-{item.level}"><a href="#{_esc(item.anchor)}">'
            f'<span>{_esc(title)}</span><span class="page">{item.page_no}</span></a></li>'
        )
    return (
        f'<nav class="toc" aria-label="{_L()["toc"]}"><h2>{_L()["toc"]}</h2><ol>'
        + "".join(items)
        + "</ol></nav>"
    )

def _source_index(spec: LectureSpec) -> str:
    rows: list[str] = []
    seen: set[str] = set()
    for sec in spec.sections:
        refs = list(sec.source_refs)
        for block in sec.blocks:
            refs.extend(block.source_refs)
            if block.figure is not None:
                refs.append(block.figure.source)
        if not refs:
            continue
        label = _pages_label(refs)
        key = f"{sec.title}|{label}"
        if key in seen:
            continue
        seen.add(key)
        rows.append(f'<tr><td>{_esc(sec.title)}</td><td>{_esc(label)}</td></tr>')
    if not rows:
        return ""
    return (f'<section class="source-index"><h2>{_L()["source_index"]}</h2>'
            f'<table><thead><tr><th>{_esc(_L()["source_section"])}</th>'
            f'<th>{_esc(_L()["source"])}</th></tr></thead><tbody>{"".join(rows)}</tbody></table></section>')


def _closing(spec: LectureSpec) -> str:
    text = (spec.closing.text or '').replace('\\n', '\n')
    parts = [p.strip() for p in text.split('\n\n') if p.strip()]
    body = ''.join(f'<p>{_para(p)}</p>' for p in parts)
    return f'<section class="closing"><h2>{_L()["closing"]}</h2>{body}</section>'


def _summary(spec: LectureSpec) -> str:
    s = spec.summary
    km = "".join(f"<li>{_esc(x)}</li>" for x in s.knowledge_map)
    ef = "".join(f"<li>{_esc(x)}</li>" for x in s.exam_focus)
    extra = ""
    if km:
        extra += f'<div class="summary-block"><h3>{_L()["knowledge"]}</h3><ul>{km}</ul></div>'
    if ef:
        extra += f'<div class="summary-block"><h3>{_L()["focus"]}</h3><ul>{ef}</ul></div>'
    how = f'<p class="how-to-use">{_para(s.how_to_use)}</p>' if s.how_to_use else ""
    return f'<section class="summary"><h2>{_L()["summary"]}</h2><p>{_para(s.overview)}</p>{extra}{how}</section>'



def _kind_label(title: str) -> str:
    text = str(title or "")
    if any(k in text for k in ("试卷", "出卷", "真题")):
        return "试卷"
    if any(k in text for k in ("提取", "考点", "名词", "术语", "原题", "逻辑")):
        return "提取"
    return "讲义"

def _header(spec: LectureSpec) -> str:
    h = spec.header
    meta: list[str] = []
    if h.target_score is not None:
        meta.append(_L()["target"].format(p=h.target_score))
    if h.days_left is not None:
        meta.append(_L()["days"].format(p=h.days_left))
    if h.foundation:
        meta.append(_L()["foundation"].format(p=h.foundation))
    if h.materials:
        meta.append(_L()["material"] + "、".join(h.materials) if LANG != "en" else _L()["material"] + ", ".join(h.materials))
    if h.coverage_scope:
        meta.append(h.coverage_scope)
    if h.generated_at:
        meta.append(h.generated_at)
    section = (
        f'<p class="subtitle">{_esc(h.section_label)}</p>' if h.section_label else ""
    )
    return (
        '<header class="lecture-header">'
        f'<p class="kicker">TermFinale精品{_kind_label(h.title)}</p>'
        f"<h1>{_esc(h.course)}</h1>"
        f'<p class="subtitle">{_esc(h.title)}</p>'
        f"{section}"
        '<p class="meta">' + " ｜ ".join(_esc(x) for x in meta) + "</p>"
        "</header>"
    )


