def render_lecture_html(spec: LectureSpec, *, full_document: bool = True) -> str:
    _set_lang(spec)
    chapter = (
        f'<h2 class="chapter-title" id="chapter-title">{_esc(spec.chapter_title)}</h2>'
        if spec.chapter_title else ""
    )
    body = (
        '<article class="lecture">'
        + _header(spec)
        + _summary(spec)
        + _toc(spec)
        + chapter
        + "".join(_section(sec, sec.level) for sec in spec.sections)
        + _closing(spec)
        + _source_index(spec)
        + '<footer class="generated-footer">'
        + _esc(_L()["footer"].format(agent=spec.footer.agent_name, material=spec.footer.material_label,
                                     coverage=f"{spec.footer.coverage_percent:g}", disclaimer=spec.footer.disclaimer))
        + '<p class="ai-note">AI 辅助生成 · 已做机器质量检查；具体内容以原始资料为准。</p>'
        + "</footer></article>"
    )
    if not full_document:
        return body
    return (
        f'<!doctype html><html lang="{ "en" if spec.language_policy.gen_lang.lower().startswith("english") else "zh-Hant" if spec.language_policy.gen_lang.startswith("繁") else "zh-CN" }"><head><meta charset="utf-8">' 
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{_esc(spec.header.title)}</title><style>{CSS}{READER_CSS}</style><!--TF_HEAD_EXTRA--></head>"
        f"<body>{reader_tools_html()}{body}<script>{READER_JS}</script><!--TF_BODY_EXTRA--></body></html>"
    )


def write_lecture_html(spec: LectureSpec, path: str | Path) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_lecture_html(spec), encoding="utf-8")
    return target
